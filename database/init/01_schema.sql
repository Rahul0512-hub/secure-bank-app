CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE IF NOT EXISTS users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    phone VARCHAR(20),
    role VARCHAR(20) NOT NULL
        CHECK (role IN ('Admin', 'Customer')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS accounts (
    account_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL
        REFERENCES users(user_id) ON DELETE RESTRICT,
    account_number VARCHAR(34) NOT NULL UNIQUE,
    account_type VARCHAR(30) NOT NULL,
    balance NUMERIC(19, 4) NOT NULL DEFAULT 0
        CHECK (balance >= 0),
    currency CHAR(3) NOT NULL DEFAULT 'INR',
    status VARCHAR(20) NOT NULL DEFAULT 'Active'
        CHECK (status IN ('Active', 'Frozen', 'Closed'))
);

CREATE TABLE IF NOT EXISTS loans (
    loan_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL
        REFERENCES users(user_id) ON DELETE RESTRICT,
    loan_amount NUMERIC(19, 4) NOT NULL
        CHECK (loan_amount > 0),
    interest_rate NUMERIC(7, 4) NOT NULL
        CHECK (interest_rate >= 0),
    status VARCHAR(20) NOT NULL DEFAULT 'Pending'
        CHECK (status IN ('Pending', 'Approved', 'Rejected', 'Active', 'Paid', 'Defaulted')),
    start_date DATE,
    end_date DATE,
    CHECK (end_date IS NULL OR start_date IS NULL OR end_date >= start_date)
);

CREATE TABLE IF NOT EXISTS transactions (
    transaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_account_id BIGINT NOT NULL
        REFERENCES accounts(account_id) ON DELETE RESTRICT,
    destination_account_id BIGINT NOT NULL
        REFERENCES accounts(account_id) ON DELETE RESTRICT,
    amount NUMERIC(19, 4) NOT NULL
        CHECK (amount > 0),
    transaction_type VARCHAR(30) NOT NULL,
    description TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'Pending'
        CHECK (status IN ('Pending', 'Completed', 'Failed', 'Reversed')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (source_account_id <> destination_account_id)
);

CREATE INDEX IF NOT EXISTS idx_accounts_user_id
    ON accounts(user_id);

CREATE INDEX IF NOT EXISTS idx_loans_user_id
    ON loans(user_id);

CREATE INDEX IF NOT EXISTS idx_transactions_source_account
    ON transactions(source_account_id);

CREATE INDEX IF NOT EXISTS idx_transactions_destination_account
    ON transactions(destination_account_id);

CREATE INDEX IF NOT EXISTS idx_transactions_created_at
    ON transactions(created_at DESC);
